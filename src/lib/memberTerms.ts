// A club's rules and consent text, shown at registration and accepted with
// the tick. Built on the paper "форма за съгласие" clubs hand out. The coach
// can rewrite it (admin panel); until then every club gets this standard
// text. Plain text: a line starting with a number is a heading, a blank
// line separates paragraphs.
export function defaultMemberTerms(club: string): string {
  return `1. Картотекиране и лични данни
${club} обработва личните данни на трениращия, за да го картотекира във федерацията и в клуба и за участие в тренировки, състезания в България и чужбина и лагери. За целта се събират: имена, ЕГН, телефон, имейл и, когато федерацията или застрахователят го изискват, адрес, медицинско свидетелство и застраховка.

2. Тренировъчен процес
Запознат съм с правилата в залите на клуба и ще ги спазвам. Трениращият следва указанията на треньора. Промени в графика клубът обявява в приложението.

3. Такси
Месечната такса и отстъпките (например за братя и сестри) са според ценоразписа на клуба. Първата тренировка е безплатна. Таксата важи от датата на плащане до същата дата на следващия месец; пропуснатите тренировки не намаляват таксата.

4. Здраве
Родителят (или пълнолетният трениращ) потвърждава, че трениращият е в добро здраве, и уведомява треньора за алергии, заболявания, травми и лекарства, като при нужда представя медицински документ. Тези данни се ползват само за безопасността на тренировките. При признаци на заболяване клубът може да не допусне трениращия до тренировка.

5. Рискове
Участието е доброволно. При тренировки и състезания по карате има риск от наранявания. Клубът отговаря за организацията и безопасността на тренировките според закона, но не носи отговорност за събития извън тренировъчния процес.

6. Оттегляне на съгласието
Мога да оттегля съгласието си по всяко време, като уведомя клуба. Оттеглянето не засяга законността на обработването дотогава. След това данните се изтриват, освен тези, които клубът е длъжен да пази по закон.`
}

export function memberTermsFor(club: { name: string; member_terms?: string | null } | null | undefined): string {
  return club?.member_terms?.trim() || defaultMemberTerms(club?.name ?? 'Клубът')
}

// Plain text -> sections for display.
export function termsBlocks(text: string): { heading: boolean; text: string }[] {
  return text
    .split(/\n+/)
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => ({ heading: /^\d+[.)]\s/.test(l) && l.length < 80, text: l }))
}
